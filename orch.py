    rc, o, e = hrun(h, f"{pueue(h)} add -g agents -l {name} -w {q(rcwd)} --print-task-id -- sh {root}/run/{name}.sh")
    if rc: return rc, o, e
    deliver_key(h, fifo, key)
    return 0, o, ""

