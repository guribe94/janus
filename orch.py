INTERP_BAD = re.compile(r"rmtree|os\.(remove|unlink|rmdir|kill|killpg)|\.unlink\(|unlink\s*\(|\bsignal\.SIG|subprocess.*\b(rm|kill|pkill)\b|system\s*\(.*\b(rm|kill)\b|do shell script.*\b(rm|kill)\b")
