class Err(Exception): pass

def now(): return time.time()
def ts(t=None): return time.strftime("%Y-%m-%d %H:%M", time.localtime(t or now()))
def say(*a): print(*a, flush=True)

# ---------------------------------------------------------------- config and state
def find_root(start=None):
    p = Path(start or os.getcwd()).resolve()
    for d in [p, *p.parents]:
        if (d / "orch.toml").is_file(): return d
    return None

class Cfg:
    def __init__(self, root):
        self.root = root
        self.c = tomllib.loads((root / "orch.toml").read_text())
        pr = self.c.get("project", {})
        self.name = pr.get("name", root.name)
        self.state = root / pr.get("state", ".orch"); self.state.mkdir(exist_ok=True)
        self.beads = root / pr.get("beads", ".")
        self.cycle = pr.get("cycle_min", 15) * 60; self.deadline = pr.get("deadline_min", 30) * 60
        self.silent = pr.get("silent_min", 30) * 60; self.unreach = pr.get("unreachable_min", 20) * 60
        self.reset_tokens = pr.get("reset_tokens", 150000)
        self.hosts = self.c.get("hosts", {}); self.prov = self.c.get("providers", {})
        self.models = self.c.get("models", {}); self.route = self.c.get("routing", {})
        self.paths = self.c.get("paths", {}); self.caps = self.c.get("caps", {})
    def p(self, k, d=""): return self.root / self.paths.get(k, d)
    def f(self, n): return self.state / n
    def jget(self, n, d=None):
        try: return json.loads(self.f(n).read_text())
        except Exception: return {} if d is None else d
    def jput(self, n, v): self.f(n).write_text(json.dumps(v))
    def touch(self, n): self.f(n).touch()
    def mtime(self, n):
        try: return self.f(n).stat().st_mtime
        except OSError: return 0

def sh(cmd, cwd=None, inp=None, timeout=25, env=None):
    try:
        r = subprocess.run(cmd, cwd=cwd, input=inp, capture_output=True, text=True, timeout=timeout,
                           env={**os.environ, **env} if env else None)
        return r.returncode, r.stdout, r.stderr
    except FileNotFoundError: return 127, "", f"{cmd[0]}: not installed"
    except subprocess.TimeoutExpired: return 124, "", f"{cmd[0]}: timeout"

def hrun(h, script, timeout=25, inp=None):
    """Run a shell script on host h (local or over ssh)."""
    if h.get("local"): return sh(["sh", "-c", script], timeout=timeout, inp=inp)
    return sh([*SSH, h["ssh"], script], timeout=timeout, inp=inp)

def X(h, script, **k):
    """Run on a host, or print in dry-run."""
    if DRY: say(f"+ [{h.get('ssh', 'local')}] {script}"); return 0, "", ""
    return hrun(h, script, **k)

def herdr(*a, timeout=20):
    rc, o, e = sh(["herdr", *a], timeout=timeout)
    try: return json.loads(o).get("result", {}) if rc == 0 else None
    except Exception: return None

def findkey(o, sub):
    if isinstance(o, dict):
        for k, v in o.items():
            if sub in k and isinstance(v, int): return v
            r = findkey(v, sub)
            if r: return r
    elif isinstance(o, list):
        for v in o:
            r = findkey(v, sub)
            if r: return r

# ---------------------------------------------------------------- beads
class Beads:
    def __init__(self, cfg): self.cfg = cfg
    def run(self, *a):
        rc, o, e = sh(["bd", *a, "--json"], cwd=self.cfg.beads)
        if rc: raise Err(f"bd {a[0]}: {(e or o).strip()[:120]}")
        try: return json.loads(o) if o.strip() else []
        except Exception: raise Err(f"bd {a[0]}: bad json")
    def issues(self, label, status="open"):
        r = self.run("list", "--label", label, "--status", status)
        return r.get("issues", r) if isinstance(r, dict) else r
    def units(self):
        out = []
        for i in self.issues("unit"):
            t = i.get("title", "")
            if not t.startswith("unit:"): continue
            try: m = json.loads(i.get("notes") or i.get("description") or "{}")
            except Exception: m = {}
            out.append({**m, "id": i["id"], "name": t[5:]})
        return out
    def save(self, u):
        meta = {k: v for k, v in u.items() if k not in ("id", "name")}
        self.run("update", u["id"], "--notes", json.dumps(meta))
    def create(self, title, label, desc=""): 
        r = self.run("create", title, "-l", label, "-d", desc)
        return (r[0] if isinstance(r, list) else r)["id"]
    def comment(self, i, text): sh(["bd", "comments", "add", i, text], cwd=self.cfg.beads)

